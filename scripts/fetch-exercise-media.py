data = {e['id']: e for e in json.load(open(sys.argv[1]))}
out_assets, out_ts = sys.argv[2], sys.argv[3]
os.makedirs(out_assets, exist_ok=True)
lines = ["// Generated by scripts/fetch-exercise-media.py from free-exercise-db (Unlicense).",
         "// https://github.com/yuhonas/free-exercise-db", "",
         "export interface ExerciseMedia {", "  /** Start and end positions, shown as an animated demo. */",
         "  frames: number[];", "  instructions: string[];", "  sourceName: string;", "}", "",
         "export const EXERCISE_MEDIA: Record<string, ExerciseMedia> = {"]
for ours, theirs in MAP.items():
    e = data[theirs]
    frames = []
    for i, img in enumerate(e['images'][:2]):
        dest = os.path.join(out_assets, f"{ours}-{i}.jpg")
        if not os.path.exists(dest):
            urllib.request.urlretrieve("https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/" + img, dest)
        frames.append(f"require('../../assets/exercises/{ours}-{i}.jpg')")
    instr = json.dumps([s.strip() for s in e['instructions'] if s.strip()], ensure_ascii=False)
    lines.append(f"  '{ours}': {{")
    lines.append(f"    frames: [{', '.join(frames)}],")
    lines.append(f"    instructions: {instr},")
    lines.append(f"    sourceName: {json.dumps(e['name'])},")
    lines.append("  },")
lines.append("};")
open(out_ts, 'w').write("\n".join(lines) + "\n")
print(len(MAP), 'mapped')
